/**
 * PostgreSQL, through one small interface the repositories use.
 *
 * - With DATABASE_URL set (Supabase, Neon, RDS or your own server) it
 *   connects with `pg`. Moving between hosts is a change of that URL.
 * - Without it (local development, tests) it runs PGlite: real Postgres,
 *   embedded, saved under DATA_DIR/pg. Same SQL either way.
 *
 * Queries use `?` placeholders (turned into $1, $2…). Timestamps come back
 * as ISO strings in UTC ("2026-10-09T13:05:00.000Z") and counts as numbers,
 * so callers read rows the same whatever the driver.
 */

export const DATA_DIR = process.env.DATA_DIR || path.join(process.cwd(), "data");

export interface Db {
  all<T>(sql: string, ...params: unknown[]): Promise<T[]>;
  get<T>(sql: string, ...params: unknown[]): Promise<T | undefined>;
  /** Insert, update or delete; `changes` is the number of rows touched. */
  run(sql: string, ...params: unknown[]): Promise<{ changes: number }>;
  /** Several statements at once, without parameters (migrations). */
  exec(sql: string): Promise<void>;
}


/** "2026-10-09 13:05:00.123+00" → "2026-10-09T13:05:00.123Z": ISO in UTC, so Date.parse reads it right anywhere. */
function utcTimestamp(value: string): string {
  const iso = value.replace(" ", "T").replace(/([+-]\d\d)$/, "$1:00");
  const date = new Date(iso);
  return Number.isNaN(date.getTime()) ? value : date.toISOString();
}

/** Type OIDs: int8, numeric, timestamptz, timestamp, date. */
const PARSERS: Record<number, (value: string) => unknown> = {
  20: (value) => Number(value),
  1700: (value) => Number(value),
  1184: utcTimestamp,
  1114: (value) => value.slice(0, 19),
  1082: (value) => value,
};

/** `?` → `$1, $2…`, skipping anything inside quotes. */
export function numberPlaceholders(sql: string): string {
  let n = 0;
  let out = "";
  let quote: string | null = null;
  for (const ch of sql) {
    if (quote) {
      if (ch === quote) quote = null;
      out += ch;
    } else if (ch === "'" || ch === '"') {
      quote = ch;
      out += ch;
    } else if (ch === "?") {
      out += `$${++n}`;
    } else {
      out += ch;
    }
  }
  return out;
}

/** Booleans are stored as 0/1 (as they were in SQLite); undefined means NULL. */
function normalise(params: unknown[]): unknown[] {
  return params.map((p) => (p === undefined ? null : typeof p === "boolean" ? (p ? 1 : 0) : p));
}

type Query = (sql: string, params: unknown[]) => Promise<{ rows: unknown[]; changes: number }>;

/** Database time within one API request, for its Server-Timing header (see http.ts handle). */
const dbTiming = new AsyncLocalStorage<{ ms: number; queries: number }>();

/** Runs `fn`, adding up the time its queries spend in the database. */
export function timeDb<T>(timing: { ms: number; queries: number }, fn: () => Promise<T>): Promise<T> {
  return dbTiming.run(timing, fn);
}

function wrap(rawQuery: Query, execMany: (sql: string) => Promise<void>): Db {
  const query: Query = async (sql, params) => {
    const timing = dbTiming.getStore();
    if (!timing) return rawQuery(sql, params);
    const started = performance.now();
    try {
      return await rawQuery(sql, params);
    } finally {
      timing.ms += performance.now() - started;
      timing.queries += 1;
    }
  };
  return {
    async all<T>(sql: string, ...params: unknown[]) {
      return (await query(numberPlaceholders(sql), normalise(params))).rows as T[];
    },
    async get<T>(sql: string, ...params: unknown[]) {
      return (await query(numberPlaceholders(sql), normalise(params))).rows[0] as T | undefined;
    },
    async run(sql: string, ...params: unknown[]) {
      return { changes: (await query(numberPlaceholders(sql), normalise(params))).changes };
    },
    exec: execMany,
  };
}

interface Driver {
  db: Db;
  transaction<T>(fn: (tx: Db) => Promise<T>): Promise<T>;
  close(): Promise<void>;
}

/**
 * TLS for a hosted database. With the provider's CA certificate
 * (DATABASE_SSL_CA: the PEM text or a file path; Supabase: Project Settings
 * → Database → SSL certificate) or DATABASE_SSL=verify (a certificate public
 * CAs sign), the server's identity is checked. Without either the link is
 * still encrypted but unchecked, and startup warns about it in production.
 */
export function databaseSsl(url: string): false | { rejectUnauthorized: boolean; ca?: string } {
  if (process.env.DATABASE_SSL === "off" || /localhost|127\.0\.0\.1/.test(url)) return false;
  const ca = process.env.DATABASE_SSL_CA?.trim();
  if (ca) return { rejectUnauthorized: true, ca: ca.includes("BEGIN CERTIFICATE") ? ca.replaceAll("\\n", "\n") : fs.readFileSync(ca, "utf8") };
  return { rejectUnauthorized: process.env.DATABASE_SSL === "verify" };
}

async function pgDriver(url: string): Promise<Driver> {
  const pg = (await import("pg")).default;
  const types = { getTypeParser: (oid: number, format?: string) => (PARSERS[oid] ? (PARSERS[oid] as (v: string) => unknown) : pg.types.getTypeParser(oid, format as "text")) };
  const pool = new pg.Pool({
    connectionString: url,
    // Serverless hosts (Vercel) run many copies of the app at once, each with
    // its own pool, so each keeps just a couple of connections; a single
    // server can keep more. Point serverless at a transaction pooler.
    max: Number(process.env.DATABASE_POOL_SIZE || (process.env.VERCEL ? 2 : 5)),
    // A warm copy keeps its connection for the next scan rather than paying
    // the TLS and pooler handshake again (on Vercel, attachDatabasePool below
    // closes idle ones before the copy is suspended).
    idleTimeoutMillis: 30_000,
    // Fail fast rather than leave a guest's page hanging on an unreachable database.
    connectionTimeoutMillis: 5_000,
    allowExitOnIdle: true,
    // Hosted Postgres (Supabase and most others) needs TLS; set DATABASE_SSL=off for a local server.
    ssl: databaseSsl(url) || undefined,
    types,
  });
  if (process.env.VERCEL) (await import("@vercel/functions")).attachDatabasePool(pool);
  const onClient = (client: { query: (text: string, values?: unknown[]) => Promise<{ rows: unknown[]; rowCount: number | null }> }): Db =>
    wrap(
      async (sql, params) => {
        const result = await client.query(sql, params);
        return { rows: result.rows, changes: result.rowCount ?? 0 };
      },
      async (sql) => {
        await client.query(sql);
      },
    );
  return {
    db: onClient(pool),
    async transaction(fn) {
      const client = await pool.connect();
      try {
        await client.query("BEGIN");
        const result = await fn(onClient(client));
        await client.query("COMMIT");
        return result;
      } catch (error) {
        await client.query("ROLLBACK").catch(() => {});
        throw error;
      } finally {
        client.release();
      }
    },
    close: () => pool.end(),
  };
}

async function pgliteDriver(): Promise<Driver> {
  const { PGlite } = await import("@electric-sql/pglite");
  const dir = process.env.PGLITE_DIR || path.join(DATA_DIR, "pg");
  if (!dir.startsWith("memory://")) fs.mkdirSync(dir, { recursive: true });
  const lite = new PGlite(dir, { parsers: PARSERS });
  await lite.waitReady;
  type Runner = { query: (sql: string, params?: unknown[]) => Promise<{ rows: unknown[]; affectedRows?: number }>; exec: (sql: string) => Promise<unknown> };
  const onRunner = (runner: Runner): Db =>
    wrap(
      async (sql, params) => {
        const result = await runner.query(sql, params);
        return { rows: result.rows, changes: result.affectedRows ?? 0 };
      },
      async (sql) => {
        await runner.exec(sql);
      },
    );
  return {
    db: onRunner(lite),
    transaction: (fn) => lite.transaction((tx) => fn(onRunner(tx))),
    close: () => lite.close(),
  };
}

async function migrate(driver: Driver) {
  const { db } = driver;
  await db.exec("CREATE TABLE IF NOT EXISTS schema_version (version INTEGER NOT NULL)");
  const row = await db.get<{ version: number }>("SELECT version FROM schema_version");
  if (!row) await db.run("INSERT INTO schema_version (version) VALUES (0)");
  let version = row?.version ?? 0;
  while (version < MIGRATIONS.length) {
    version = await driver.transaction(async (tx) => {
      // Several servers (or serverless copies) can start at once: one runs
      // each update while the others wait, then see it's done.
      await tx.get("SELECT pg_advisory_xact_lock(7262021)");
      const current = (await tx.get<{ version: number }>("SELECT version FROM schema_version"))?.version ?? 0;
      if (current >= MIGRATIONS.length) return current;
      await tx.exec(MIGRATIONS[current]);
      await tx.run("UPDATE schema_version SET version = ?", current + 1);
      return current + 1;
    });
  }
}

declare global {
  // One connection (or pool) for the process, kept across dev hot reloads.
  var __appDriver: Promise<Driver> | undefined;
  var __appDriverMigrations: number | undefined;
}

/**
 * One round trip that usually ends a cold start's setup: the schema is
 * current and this version of the demos is already in. Anything else
 * (a fresh database, a new migration, new demo content) takes the full path.
 */
async function upToDate(db: Db): Promise<boolean> {
  try {
    const row = await db.get<{ version: number | null; seeded: boolean }>(
      "SELECT (SELECT max(version) FROM schema_version) AS version, EXISTS (SELECT 1 FROM job_runs WHERE job = 'demo-seed' AND key = ?) AS seeded",
      DEMO_SEED_VERSION,
    );
    return row?.version === MIGRATIONS.length && !!row.seeded;
  } catch {
    return false; // no tables yet
  }
}

async function open(): Promise<Driver> {
  const url = process.env.DATABASE_URL;
  const driver = url ? await pgDriver(url) : await pgliteDriver();
  if (!(await upToDate(driver.db))) {
    await migrate(driver);
    await seedDemoVenues(driver.db);
  }
  return driver;
}

function driver(): Promise<Driver> {
  // A hot reload can bring new migrations while the connection lives on.
  if (!globalThis.__appDriver || globalThis.__appDriverMigrations !== MIGRATIONS.length) {
    const previous = globalThis.__appDriver;
    globalThis.__appDriver = previous ? previous.then(async (d) => (await migrate(d), await seedDemoVenues(d.db), d)) : open();
    globalThis.__appDriverMigrations = MIGRATIONS.length;
    // A failed start (e.g. a wrong DATABASE_URL) is retried on the next request.
    globalThis.__appDriver.catch(() => {
      globalThis.__appDriver = undefined;
    });
  }
  return globalThis.__appDriver;
}

const activeTx = new AsyncLocalStorage<Db>();

/** The database: inside `transaction()`, the transaction's connection. */
export async function getDb(): Promise<Db> {
  return activeTx.getStore() ?? (await driver()).db;
}

/**
 * Runs `fn` in a transaction. Anything called inside it that uses getDb()
 * joins the same transaction, so repositories compose without passing it on.
 */
export async function transaction<T>(fn: (db: Db) => Promise<T>): Promise<T> {
  const current = activeTx.getStore();
  if (current) return fn(current);
  return (await driver()).transaction((tx) => activeTx.run(tx, () => fn(tx)));
}

/** Closes the connection; the next getDb() opens a fresh one. For tests and shutdown. */
export async function closeDb(): Promise<void> {
  const current = globalThis.__appDriver;
  globalThis.__appDriver = undefined;
  globalThis.__appDriverMigrations = undefined;
  if (current) await (await current).close();
}
